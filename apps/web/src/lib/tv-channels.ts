export function getChannelBySlug(slug?: string | null): TvChannel | undefined {
  if (!slug || typeof slug !== "string") return undefined;
  const normalized = slug.trim().toLowerCase();
  return (
    TV_CHANNELS.find((c) => c.slug.toLowerCase() === normalized) ||
    TV_CHANNELS.find((c) => c.id.toLowerCase() === normalized) ||
    TV_CHANNELS.find((c) => c.shortName.toLowerCase() === normalized)
  );
}

export function getDefaultChannel(): TvChannel {
  return TV_CHANNELS[0]; // VTV1 HD
}
