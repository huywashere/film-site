export function getUniverseTimeline(
  universe: "marvel" | "dc",
  options?: {
    mode?: "chronological" | "release";
    phase?: string;
    search?: string;
  }
): TimelineFilmItem[] {
  const base = universe === "marvel" ? MARVEL_TIMELINE_FILMS : DC_TIMELINE_FILMS;
  let list = [...base];

  if (options?.phase && options.phase !== "all") {
    list = list.filter((f) => f.phase === options.phase);
  }

  if (options?.search && options.search.trim()) {
    const q = options.search
      .trim()
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/đ/g, "d");
    list = list.filter((f) => {
      const text = `${f.name} ${f.origin_name} ${f.timelineYear} ${f.phaseLabel} ${f.contextNote}`
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/đ/g, "d");
      return text.includes(q);
    });
  }

  const mode = options?.mode || "chronological";
  if (mode === "chronological") {
    list.sort((a, b) => a.chronoOrder - b.chronoOrder);
  } else {
    list.sort((a, b) => a.releaseOrder - b.releaseOrder);
  }

  return list;
}
